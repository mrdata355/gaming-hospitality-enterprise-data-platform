-- Synthetic DB2 extraction catalog for portfolio demonstration.
-- Library and object names are generated, not internal Venetian identifiers.
SET CURRENT DEGREE = 'ANY';

-- HOSPITALITY.RESERVATION: bounded watermark extract
SELECT
    RESERVATION_ID AS SOURCE_BUSINESS_KEY,
    GUEST_ID,
    PROPERTY_CODE,
    ARRIVAL_DATE,
    DEPARTURE_DATE,
    STATUS_CD,
    ROOM_TYPE_CD,
    ROOM_QTY,
    REVENUE_AMT,
    UPDATED_TS,
    UPDATED_SCN AS SOURCE_WATERMARK
FROM HOSPITALITY.RESERVATION
WHERE UPDATED_SCN > CAST(? AS BIGINT)
  AND UPDATED_SCN <= CAST(? AS BIGINT)
WITH UR;

SELECT COALESCE(MAX(UPDATED_SCN),0) AS HIGH_WATERMARK
FROM HOSPITALITY.RESERVATION
WITH UR;

SELECT RESERVATION_ID,COUNT(*) AS DUP_COUNT
FROM HOSPITALITY.RESERVATION
GROUP BY RESERVATION_ID
HAVING COUNT(*) > 1
WITH UR;

